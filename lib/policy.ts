/* ============================================================
 * DECISION POLICY (single source of truth, used by verdict.ts, the server and the tests)
 *
 *  Action      meaning                                         minimum risk forced
 *  LOCK        system freezes the case, nobody can release it   70
 *  REVIEW      supervisor must review (override needs PIN)      50 (critical) / 40 (high)
 *  SUPPORT     supporting evidence only: adds points, but it    0
 *              can never trigger a review or a lock alone
 * ============================================================ */
export const HARD_LOCK_RISK = 70
export const REVIEW_RISK = 40

export type Severity = 'critical' | 'high' | 'medium' | 'info'
export type FlagCode =
  | 'ELA_ANOMALY' | 'MRZ_CHECKSUM' | 'SIG_INVALID' | 'QR_MISMATCH' | 'FACE_MISMATCH' | 'LIVENESS_FAIL'
  | 'AADHAAR_CHECKSUM' | 'DOC_SIG_BROKEN' | 'UNREADABLE' | 'AI_GENERATED' | 'META_SUSPECT' | 'SOURCE_NOTE' | 'UNVERIFIED' | 'SIGNED_DATA_MISMATCH'

export type Action = 'LOCK' | 'REVIEW' | 'SUPPORT'

/** Forced minimum risk for each (code, severity). Anything not listed is SUPPORT (0). */
export const FLOOR: Partial<Record<FlagCode, Partial<Record<Severity, number>>>> = {
  // signature of a TRUSTED certificate does not match: the strongest evidence there is
  SIG_INVALID: { critical: HARD_LOCK_RISK, high: 50 }, // high = certificate not trusted, so it may just be the wrong certificate
  // File metadata can be edited or copied; even an AI marker needs human review, not an automatic lock.
  AI_GENERATED: { high: REVIEW_RISK },
  // A trusted Aadhaar signature contradicting high-confidence printed data is decisive.
  QR_MISMATCH: { critical: 55 },
  // Only a trusted government signature plus a high-confidence printed-data mismatch is decisive.
  SIGNED_DATA_MISMATCH: { critical: HARD_LOCK_RISK },
  // PDF content changed after signing: high-priority review
  DOC_SIG_BROKEN: { critical: 60, high: 40 },
  // invalid checksum: suspicious, OCR can misread a digit
  AADHAAR_CHECKSUM: { critical: 50 },
  MRZ_CHECKSUM: { critical: 45 },
  UNREADABLE: { critical: 50 }, // impossible date of birth
  FACE_MISMATCH: { critical: 55 },
  LIVENESS_FAIL: { critical: 55 },
  // an Aadhaar whose UIDAI signature and QR-to-print match were NOT verified goes to human review.
  // Change this line to { medium: 0 } if you want unverified cards to stay at low risk.
  UNVERIFIED: { medium: REVIEW_RISK },
  // an editing program named in the file (Photoshop, GIMP...) on a government document: never accepted silently, goes to review.
  // A genuine government document is not normally edited in an image editor. Metadata alone can still be wrong,
  // so this is REVIEW (a human decides), never LOCK.
  META_SUSPECT: { high: REVIEW_RISK },
  // AI metadata markers, ELA_ANOMALY, SOURCE_NOTE, and medium META_SUSPECT are not proof and cannot lock alone.
}

export function floorFor(code: FlagCode, sev: Severity): number {
  return FLOOR[code]?.[sev] ?? 0
}

export function actionFor(code: FlagCode, sev: Severity): Action {
  const f = floorFor(code, sev)
  return f >= HARD_LOCK_RISK ? 'LOCK' : f >= REVIEW_RISK ? 'REVIEW' : 'SUPPORT'
}

/** RED = evidence that something was EDITED, generated by AI, or tampered with. Anything else (not verified, unreadable,
 * source notes, failed checksum, untrusted certificate) is shown AMBER as "needs review", never as a red flag. */
export function isTamperEvidence(code: FlagCode, sev: Severity): boolean {
  if (code === 'ELA_ANOMALY' || code === 'AI_GENERATED' || code === 'DOC_SIG_BROKEN' || code === 'SIGNED_DATA_MISMATCH') return true
  if (code === 'QR_MISMATCH') return sev === 'critical' // signed data differs from printed data
  if (code === 'SIG_INVALID') return sev === 'critical' // signature of a TRUSTED certificate does not match
  if (code === 'META_SUSPECT') return sev === 'high' // an image editor is named in the file
  return false
}
